"""From a compiled design to a bitstream on a real board: the open ECP5 flow, or Vivado for Kria."""

import json
import pathlib
import shutil
import subprocess

from .errors import Onnx2FpgaError
from .p6_emit.hardcaml import HardcamlGenerator


class BoardError(Onnx2FpgaError):
    pass


class IcepiZero:
    """The Icepi Zero: ECP5 LFE5U-25F-6CABGA256, 50 MHz oscillator, FT231X for programming and serial."""

    NAME = "icepi_zero"
    DEVICE = "icepi25"
    REVISIONS = ("v1.0", "v1.1", "v1.2", "v1.3", "v1.4")
    VCO_MHZ = 480
    DEFAULT_MHZ = 20
    DEFAULT_BAUD = 1_000_000
    DEPTH = 2048
    # Where the board's tools usually are when they are not on PATH.
    TOOL_DIRS = ("~/.local/opt/oss-cad-suite/bin", "/opt/oss-cad-suite/bin")
    FLOW_TIMEOUT = 3600

    # usb: the FT231X's own TXD and RXD. header: pins 8 and 10, a Raspberry Pi's UART.
    UARTS = ("usb", "header")

    def __init__(self, out, rev="v1.4", mhz=DEFAULT_MHZ, baud=DEFAULT_BAUD,
                 seeds=(1, 2, 3, 4, 5, 6, 7, 8), uart="usb", generator=None):
        if rev not in self.REVISIONS:
            raise BoardError("unknown Icepi Zero revision %r, expected one of %s"
                             % (rev, ", ".join(self.REVISIONS)))
        if uart not in self.UARTS:
            raise BoardError("uart must be usb or header, not %r" % uart)
        if mhz < 4 or self.VCO_MHZ % mhz:
            raise BoardError("%d MHz does not divide the 480 MHz PLL" % mhz)
        clocks = round(mhz * 1e6 / baud)
        if clocks < 4 or abs(clocks * baud / (mhz * 1e6) - 1) > 0.02:
            raise BoardError("%d MHz cannot make %d baud within 2 percent" % (mhz, baud))
        self.out = pathlib.Path(out)
        self.rev, self.mhz, self.baud, self.seeds = rev, mhz, baud, tuple(seeds)
        self.uart = uart
        self.generator = generator or HardcamlGenerator()

    @property
    def directory(self):
        """hardware/boards/icepi_zero, next to the Hardcaml project."""
        project = self.generator.project
        if project is None:
            raise BoardError("no Hardcaml project, so no board files")
        return project.parent / "boards" / self.NAME

    @property
    def build(self):
        return self.out / self.NAME

    @property
    def bitstream(self):
        suffix = "-header" if self.uart == "header" else ""
        return self.build / ("%s%s.bit" % (self.rev, suffix))

    @classmethod
    def tool(cls, name):
        found = shutil.which(name)
        if found:
            return found
        for directory in cls.TOOL_DIRS:
            candidate = pathlib.Path(directory).expanduser() / name
            if candidate.is_file():
                return str(candidate)
        return None

    @classmethod
    def missing_tools(cls):
        return [name for name in ("yosys", "nextpnr-ecp5", "ecppack")
                if cls.tool(name) is None]

    def variables(self):
        values = {
            "DESIGN": (self.out / "design.json").resolve(),
            "BUILD": self.build.resolve(),
            "REV": self.rev,
            "UART": self.uart,
            "MHZ": self.mhz,
            "BAUD": self.baud,
            "RX_DEPTH": self.DEPTH,
            "TX_DEPTH": self.DEPTH,
            "SEEDS": " ".join(str(seed) for seed in self.seeds),
            "GENERATE": self.generator.executable,
        }
        for variable, name in (("YOSYS", "yosys"), ("NEXTPNR", "nextpnr-ecp5"),
                               ("ECPPACK", "ecppack"), ("LOADER", "openFPGALoader")):
            found = self.tool(name)
            if found:
                values[variable] = found
        return values

    def write(self):
        """A Makefile in the build directory that remembers the settings of this build."""
        self.build.mkdir(parents=True, exist_ok=True)
        lines = ["# Generated by onnx2fpga bitstream. make, make prog, make report."]
        lines += ["%s := %s" % (key, value) for key, value in self.variables().items()]
        lines.append("include %s" % (self.directory / "Makefile").resolve())
        makefile = self.build / "Makefile"
        makefile.write_text("\n".join(lines) + "\n")
        return makefile

    def run(self, target="bit"):
        missing = self.missing_tools()
        if missing:
            raise BoardError("%s not found on PATH or in %s"
                             % (", ".join(missing), ", ".join(self.TOOL_DIRS)))
        self.write()
        completed = subprocess.run(["make", "-C", str(self.build), target],
                                   capture_output=True, text=True,
                                   timeout=self.FLOW_TIMEOUT)
        if completed.returncode != 0:
            said = completed.stdout.strip().splitlines()[-8:]
            raise BoardError("the %s flow failed in %s:\n%s\n%s" % (
                self.NAME, self.build, "\n".join(said), completed.stderr[-2000:].strip()))
        return completed.stdout

    def report(self):
        """fmax and utilisation from the run that met timing."""
        report = json.loads((self.build / "report.json").read_text())
        fmax = next(iter(report["fmax"].values()))
        used = {name: (entry["used"], entry["available"])
                for name, entry in report["utilization"].items() if entry["used"]}
        return {"fmax_mhz": fmax["achieved"], "constraint_mhz": fmax["constraint"],
                "utilisation": used}

    def render_report(self):
        report = self.report()
        lines = ["fmax  %.2f MHz, clocked at %d MHz" % (report["fmax_mhz"], self.mhz)]
        for name in ("TRELLIS_COMB", "TRELLIS_FF", "TRELLIS_RAMW", "MULT18X18D",
                     "DP16KD", "EHXPLLL", "TRELLIS_IO"):
            if name in report["utilisation"]:
                used, available = report["utilisation"][name]
                lines.append("%-13s %6d / %-6d %3.0f%%"
                             % (name, used, available, 100.0 * used / available))
        return "\n".join(lines)

    def host_command(self):
        port = " --port PORT_OF_YOUR_ADAPTER" if self.uart == "header" else ""
        return "python3 %s %s%s" % (self.directory / "host.py", self.out, port)


class Kria:
    """A K26 SOM carrier built with Vivado in batch mode: the PS, an AXI4-Lite register shell and a fixed latency design."""

    NAME = None
    DEVICE = "k26"
    PART = "xck26-sfvc784-2LV-c"
    # M_AXI_HPM0_FPD, where the PS sees the shell's 64 KiB window.
    BASE = 0xA0000000
    SPAN = 0x10000
    SFP = False
    FILES = ("build.tcl", "kria.xdc", "kria_top.v")
    FLOW_TIMEOUT = 4 * 3600

    def __init__(self, out, jobs=8, generator=None):
        self.out = pathlib.Path(out)
        self.jobs = jobs
        self.generator = generator or HardcamlGenerator()

    @property
    def directory(self):
        """hardware/boards/kria, next to the Hardcaml project."""
        project = self.generator.project
        if project is None:
            raise BoardError("no Hardcaml project, so no board files")
        return project.parent / "boards" / "kria"

    @property
    def build(self):
        return self.out / self.NAME

    @property
    def bitstream(self):
        return self.build / ("%s.bit" % self.NAME)

    @property
    def timing(self):
        return self.build / "timing_summary.rpt"

    @staticmethod
    def tool(name):
        return shutil.which(name)

    @classmethod
    def missing_tools(cls):
        return [] if shutil.which("vivado") else ["vivado"]

    def command(self):
        return ["vivado", "-mode", "batch", "-nojournal", "-log", "vivado.log",
                "-source", "build.tcl"]

    def write(self):
        """The Vivado project sources in the build directory, and the register map in manifest.json."""
        self.build.mkdir(parents=True, exist_ok=True)
        design = (self.out / "design.json").resolve()
        (self.build / "kria_shell.v").write_text(self.generator.verilog(design, "kria"))
        for name in self.FILES + (("sfp.xdc",) if self.SFP else ()):
            shutil.copyfile(self.directory / name, self.build / name)
        (self.build / "settings.tcl").write_text(
            "set board %s\nset part %s\nset base 0x%08X\nset jobs %d\nset sfp %d\n"
            % (self.NAME, self.PART, self.BASE, self.jobs, self.SFP))
        described = json.loads(design.read_text())
        widths = {stream["name"]: stream["width"] for stream in described["streams"]}
        path = self.out / "manifest.json"
        manifest = json.loads(path.read_text())
        manifest["registers"] = registers(widths[described["input"]],
                                          widths[described["output"]],
                                          described["latency"], self.BASE, self.SPAN,
                                          manifest["weights"].get("words", 0))
        path.write_text(json.dumps(manifest, indent=2) + "\n")
        return self.build / "build.tcl"

    def run(self):
        self.write()
        completed = subprocess.run(self.command(), cwd=self.build, capture_output=True,
                                   text=True, timeout=self.FLOW_TIMEOUT)
        if completed.returncode != 0:
            said = completed.stdout.strip().splitlines()[-8:]
            raise BoardError("vivado failed in %s:\n%s" % (self.build, "\n".join(said)))
        return completed.stdout


class KV260(Kria):
    """The KV260 vision kit; it has no SFP+ cage, so no 10G network."""

    NAME = "kv260"


class KR260(Kria):
    """The KR260 robotics kit; its SFP+ cage is reserved in sfp.xdc for spec 007 stage B."""

    NAME = "kr260"
    SFP = True


BOARDS = {board.NAME: board for board in (IcepiZero, KV260, KR260)}


# Byte offsets of kria_regs.ml, which must agree with its Offset module.
OFFSETS = {"id": 0x0000, "latency": 0x0004, "feature_bits": 0x0008,
           "prediction_bits": 0x000C, "control": 0x0010, "status": 0x0014, "cycles": 0x0018,
           "weights_words": 0x0020, "weights_commit": 0x0024, "weights_bank": 0x0028,
           "weights_version": 0x002C, "weights_crc": 0x0030, "weights_idle_crc": 0x0034,
           "features": 0x1000, "prediction": 0x2000, "weights": 0x8000}


def registers(feature_bits, prediction_bits, latency, base, span, words=0):
    """The AXI4-Lite map of kria_regs.ml; `words` is the size of a weight bank, 0 when frozen."""
    def words_of(bits):
        return (bits + 31) // 32

    entries = {
        "id": {"access": "r", "value": 0x4F544631},
        "latency": {"access": "r", "value": latency},
        "feature_bits": {"access": "r", "value": feature_bits},
        "prediction_bits": {"access": "r", "value": prediction_bits},
        "control": {"access": "w", "meaning": "write 1 to start an inference"},
        "status": {"access": "r", "meaning": "bit 0 is set once the prediction has arrived"},
        "cycles": {"access": "r", "meaning": "cycles from the last start to its prediction"},
        "weights_words": {"access": "r", "value": words},
        "weights_commit": {"access": "w",
                           "meaning": "write 1 to make the idle bank active"},
        "weights_bank": {"access": "r", "meaning": "the active bank, 0 or 1"},
        "weights_version": {"access": "r", "meaning": "commits since configuration"},
        "weights_crc": {"access": "r",
                        "meaning": "zlib CRC-32 of the words written to the active bank "
                                   "since the last write to its word 0"},
        "weights_idle_crc": {"access": "r",
                             "meaning": "the same CRC for the idle bank, to check before "
                                        "committing"},
        "features": {"access": "rw", "words": words_of(feature_bits)},
        "prediction": {"access": "r", "words": words_of(prediction_bits)},
        "weights": ({"access": "w", "words": words,
                     "meaning": "the idle bank, one value per word, laid out as "
                                "manifest.json's weights section says"}
                    if words else
                    {"access": "reserved", "words": 0x2000,
                     "meaning": "frozen weights; writes are ignored"}),
    }
    return {
        "bus": "axi4-lite",
        "base": base,
        "span": span,
        "word_bits": 32,
        "map": {name: dict(offset=OFFSETS[name], **entry) for name, entry in entries.items()},
    }
