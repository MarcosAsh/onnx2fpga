"""The top-level SystemVerilog module, which only wires the hand-written units together."""

HEADER = ("// Generated by onnx2fpga; compute lives in the hand-written modules "
          "under hardware/rtl.")


def identifier(name):
    return "".join(c if c.isalnum() or c == "_" else "_" for c in name)


def span(width):
    return "" if width <= 1 else "[%d:0] " % (width - 1)


def literal(value):
    if isinstance(value, str):
        return '"%s"' % value
    if isinstance(value, bool):
        return "1'b1" if value else "1'b0"
    return str(int(value))


def instance(module, name, params, connections):
    if params:
        lines = ["    %s #(" % module,
                 ",\n".join("        .%s(%s)" % (key, literal(value))
                            for key, value in params.items()),
                 "    ) %s (" % name]
    else:
        lines = ["    %s %s (" % (module, name)]
    lines.append(",\n".join("        .%s(%s)" % item for item in connections.items()))
    lines.append("    );")
    return "\n".join(lines)


def render_top(graph, name):
    boundary = dict.fromkeys(graph.inputs, "s")
    boundary.update(dict.fromkeys(graph.outputs, "m"))

    def net(tensor, signal):
        return "%s_%s" % (boundary.get(tensor, tensor), signal)

    in_width = graph.tensor(graph.inputs[0]).stream_width
    out_width = graph.tensor(graph.outputs[0]).stream_width
    ports = ["input  wire clk", "input  wire rst_n",
             "input  wire %ss_tdata" % span(in_width), "input  wire s_tvalid",
             "output logic s_tready",
             "output logic %sm_tdata" % span(out_width), "output logic m_tvalid",
             "input  wire m_tready"]
    lines = [HEADER, "`default_nettype none", "", "module %s (" % name,
             ",\n".join("    " + port for port in ports), ");"]
    nodes = graph.topological_order()
    for node in nodes:
        for tensor in node.outputs:
            if tensor not in boundary:
                width = graph.tensor(tensor).stream_width
                lines.append("    logic %s%s;" % (span(width), net(tensor, "tdata")))
                lines.append("    logic %s;" % net(tensor, "tvalid"))
                lines.append("    logic %s;" % net(tensor, "tready"))
    lines.append("")
    for node in nodes:
        lines.append(instance(node.module, "u_" + identifier(node.name),
                              node.sv_params(graph), node.sv_connections(graph, net)))
        lines.append("")
    lines += ["endmodule", "", "`default_nettype wire"]
    return "\n".join(lines) + "\n"
